function pascalCase(type: string): string {
  return type.replace(/-./g, s => s[1].toUpperCase()).replace(/^[a-z]/, s => s.toUpperCase())
}

function kebabCase(type: string): string {
  return type.replace(/([A-Z])/g, '-$1').toLowerCase().replace(/^-/, '')
}

function cssSelector(type: string): string {
  const map: Record<string, string> = {
    hero: 'block-main-hero',
    aspirations: 'aspirations-viewport',
    vision: 'vision-section',
  }
  return map[type] || `block-${kebabCase(type)}`
}

// ─── Parse block types from source file ────────────────────────────────────
const src = readFileSync(BLOCK_TYPES_PATH, 'utf-8')

// Extract the BLOCK_TYPES object keys by finding lines like "  hero: {"
const blockTypeMatch = src.match(/export const BLOCK_TYPES\s*=\s*\{([\s\S]*?)\n\};/)
if (!blockTypeMatch) {
  console.error('Could not parse BLOCK_TYPES from blockTypes.js')
  process.exit(1)
}

const blockTypesBody = blockTypeMatch[1]
const typeRegex = /^  (\w+):\s*\{/gm
const types: string[] = []
let m
while ((m = typeRegex.exec(blockTypesBody)) !== null) {
  types.push(m[1])
}

types.sort()

// ─── Collect per-block metadata from the AST-like parse ───────────────────
// Extract label, category, animations, field count for each type
interface BlockMeta {
  label: string
  category: string
  animations: string
  fieldCount: number
  hasAnimationField: boolean
}

const meta: Record<string, BlockMeta> = {}

// Simple regex-based extraction per block
for (const t of types) {
  // Find this block's definition block
  const blockStart = new RegExp(`\\s+${t}:\\s*\\{`)
  const matchStart = src.match(blockStart)
  if (!matchStart) continue

  const startIdx = matchStart.index!
  // Find the matching closing brace by counting depth
  let depth = 0
  let endIdx = startIdx
  for (let i = startIdx; i < src.length; i++) {
    if (src[i] === '{') depth++
    if (src[i] === '}') {
      depth--
      if (depth === 0) { endIdx = i + 1; break }
    }
  }

  const blockDef = src.slice(startIdx, endIdx)

  const labelMatch = blockDef.match(/label:\s*"([^"]+)"/)
  const categoryMatch = blockDef.match(/category:\s*"([^"]+)"/)
  const animMatch = blockDef.match(/animations:\s*"([^"]+)"/)

  // Count schema entries
  const schemaStart = blockDef.match(/schema:\s*\[/)
  let fieldCount = 0
  if (schemaStart) {
    const schemaEnd = blockDef.lastIndexOf(']')
    // Match field lines with key
    const fields = blockDef.slice(schemaStart.index).match(/\{ key:/g)
    if (fields) fieldCount = fields.length
  }

  const hasAnim = blockDef.includes("type: 'animation'") || blockDef.includes('type: "animation"')

  meta[t] = {
    label: labelMatch?.[1] || t,
    category: categoryMatch?.[1] || 'content',
    animations: animMatch?.[1] || 'wrapper',
    fieldCount,
    hasAnimationField: hasAnim,
  }
}

